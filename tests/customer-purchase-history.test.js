assert.equal(permissionsContext.canPerformPageAction('view','customers',{level:2},[{page_key:'contacts',warehouse_id:2,can_view:true}]),false);
assert.equal(permissionsContext.canPerformPageAction('edit','customers',{level:2},[{page_key:'contacts',warehouse_id:1,can_view:true,can_edit:false}]),false);
assert.match(app,/customerPurchaseState===state/,'Discard responses from earlier requests');
assert.match(app,/input.focus\(\{preventScroll:true\}\)/,'Async summary refresh must preserve typing focus');
