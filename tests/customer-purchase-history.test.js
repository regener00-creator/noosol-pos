assert.equal(tier(120000,12).average,10000);
assert.equal(tier(600000,12).label,'ลูกค้าพิเศษ');
assert.match(sql,/stable security invoker/i);
assert.match(sql,/auth.uid\(\) is null or not public.can_current_user_page\('contacts'/);
assert.match(sql,/revoke all on function[\s\S]+from public,anon/);
assert.match(sql,/create index if not exists sales_customer_date_idx/);
assert.match(sql,/current_timestamp at time zone 'Asia\/Bangkok'/);
assert.match(sql,/extract\(month from v_today\)/);
assert.match(sql,/s\.sale_date>=make_date\(v_year,1,1\) and s\.sale_date<=v_today/);
