const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const file=fs.readdirSync(path.join(root,'supabase/migrations')).find(name=>name.endsWith('_customer_purchase_history.sql'));
const sql=fs.readFileSync(path.join(root,'supabase/migrations',file),'utf8');
const context=vm.createContext({});
vm.runInContext(app.slice(app.indexOf('function customerTierFromPurchases('),app.indexOf('function customerPurchaseLoad(')),context);
const tier=context.customerTierFromPurchases;
assert.equal(tier(90000,9).label,'ลูกค้าประจำ');
assert.equal(tier(89999.99,9).label,'ลูกค้าทั่วไป');
assert.equal(tier(450000,9).label,'ลูกค้าพิเศษ');
