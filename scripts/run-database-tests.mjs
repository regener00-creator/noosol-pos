import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import net from 'node:net';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import EmbeddedPostgres from 'embedded-postgres';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const directory=await fs.mkdtemp(path.join(os.tmpdir(),'pepos-isolated-pg-'));
const probe=net.createServer(); await new Promise(resolve=>probe.listen(0,'127.0.0.1',resolve));
const port=probe.address().port; await new Promise(resolve=>probe.close(resolve));
const postgresLogs=[];
const rememberLog=message=>{ postgresLogs.push(String(message)); if(postgresLogs.length>20) postgresLogs.shift(); };
const postgres=new EmbeddedPostgres({databaseDir:directory,port,user:'postgres',password:'isolated-test-only',persistent:true,
  initdbFlags:['--encoding=UTF8','--locale=C'],
  postgresFlags:['-h','127.0.0.1'],onLog:rememberLog,onError:rememberLog});
let client;
let windowsPgCtl;
try{
  await postgres.initialise();
  if(process.platform==='win32'){
    // pg_ctl manages the Windows child token and startup/stop timeouts; directly
    // spawning postgres from an elevated terminal is rejected by PostgreSQL.
    const requirePostgres=createRequire(import.meta.resolve('embedded-postgres'));
    const binaries=await import(pathToFileURL(requirePostgres.resolve('@embedded-postgres/windows-x64')).href);
    windowsPgCtl=path.join(path.dirname(binaries.postgres),'pg_ctl.exe');
    await promisify(execFile)(windowsPgCtl,['start','-D',directory,'-l',path.join(directory,'server.log'),'-o',`-h 127.0.0.1 -p ${port}`,'-w','-t','20'],{windowsHide:true,timeout:25000});
  }else await postgres.start();
  client=postgres.getPgClient('postgres','127.0.0.1'); await client.connect();
  await client.query(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create role authenticator; create role supabase_auth_admin;
    create schema auth; create schema extensions; create schema cron;
    create extension pgcrypto with schema extensions;
    create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}',raw_app_meta_data jsonb default '{}',created_at timestamptz default now());
    create table auth.sessions(id uuid primary key,user_id uuid references auth.users);
    create function auth.uid() returns uuid language sql stable as 'select nullif(current_setting(''request.jwt.claim.sub'',true),'''')::uuid';
    create function auth.role() returns text language sql stable as 'select nullif(current_setting(''request.jwt.claim.role'',true),'''')';
    create function auth.jwt() returns jsonb language sql stable as 'select coalesce(nullif(current_setting(''request.jwt.claims'',true),''''),''{}'')::jsonb';
    grant usage on schema public,auth,extensions to anon,authenticated,service_role;
    alter default privileges in schema public grant select,insert,update,delete on tables to authenticated,service_role;
    alter default privileges in schema public grant usage,select on sequences to authenticated,service_role;
    create table cron.job(jobid bigint generated by default as identity primary key,jobname text unique,schedule text,command text);
    create table cron.job_run_details(jobid bigint,start_time timestamptz);
    create function cron.schedule(text,text,text) returns bigint language plpgsql as $$declare n bigint; begin insert into cron.job(jobname,schedule,command) values($1,$2,$3) on conflict(jobname) do update set schedule=$2,command=$3 returning jobid into n; return n; end$$;
    create function cron.unschedule(bigint) returns boolean language sql as 'delete from cron.job where jobid=$1 returning true';
    create publication supabase_realtime;
  `);
  for(const folder of ['baseline','migrations']){
    const dir=path.join(root,'supabase',folder);
    for(const file of (await fs.readdir(dir)).filter(f=>f.endsWith('.sql')).sort()){
      // Only pg_cron's scheduler is mocked locally; all business SQL, constraints,
      // triggers, RLS and transaction behavior run on real PostgreSQL 17.
      const sql=(await fs.readFile(path.join(dir,file),'utf8')).replace(/\r\n/g,'\n').replace(/create extension if not exists pg_cron(?:\s+with schema \w+)?\s*;/gi,'');
      try{ await client.query(sql); }
      catch(error){ throw new Error(`Migration ${file}: ${error.message}`,{cause:error}); }
    }
  }
  console.log('All baseline and migration SQL applied to isolated PostgreSQL');
  const offlineSuite=await import('../tests/offline-sales-database.mjs');
  await offlineSuite.run({client});
  if(!process.argv.includes('--offline-only')){
  const exchangeSuite=await import('../tests/product-exchange-database.mjs');
  await exchangeSuite.run({client});
  if(!process.argv.includes('--exchange-only')){
  const returnsSuite=await import('../tests/customer-returns-database.mjs');
  await returnsSuite.run({client});
  const suite=await import('../tests/database-integrity.mjs');
  await suite.run({client,connect:async()=>{const c=postgres.getPgClient('postgres','127.0.0.1');await c.connect();return c;}});
  const barcodeSuite=await import('../tests/product-barcode-integrity.mjs');
  await barcodeSuite.run({client,connect:async()=>{const c=postgres.getPgClient('postgres','127.0.0.1');await c.connect();return c;}});
  const unusedUnitSuite=await import('../tests/unused-product-unit-database.mjs');
  await unusedUnitSuite.run({client,connect:async()=>{const c=postgres.getPgClient('postgres','127.0.0.1');await c.connect();return c;}});
  const catalogSuite=await import('../tests/catalog-validation-database.mjs');
  await catalogSuite.run({client});
  }
  }
}catch(error){
  // Surface the actual failure even if the platform is slow to stop Postgres.
  if(windowsPgCtl) console.error(await fs.readFile(path.join(directory,'server.log'),'utf8').catch(()=>''));
  console.error(error||postgresLogs.join('\n'));
  throw error||new Error('Isolated PostgreSQL failed to start: '+postgresLogs.join('\n'));
}finally{
  await client?.end();
  if(windowsPgCtl){
    if(!directory.startsWith(path.join(os.tmpdir(),'pepos-isolated-pg-'))) throw new Error('Unsafe test cluster path');
    if(await fs.access(path.join(directory,'postmaster.pid')).then(()=>true,()=>false))
      await promisify(execFile)(windowsPgCtl,['stop','-D',directory,'-m','fast','-w','-t','15'],{windowsHide:true,timeout:20000});
  }else await postgres.stop();
  // Only remove the exact newly-created test cluster, never an env-provided path.
  if(directory.startsWith(path.join(os.tmpdir(),'pepos-isolated-pg-'))) await fs.rm(directory,{recursive:true,force:true,maxRetries:8,retryDelay:250});
}
